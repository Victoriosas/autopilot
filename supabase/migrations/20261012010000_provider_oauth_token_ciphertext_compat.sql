-- Reconcile the deployed plaintext OAuth-token schema with application-side AES-256-GCM storage.
-- Existing plaintext credentials are never relabelled as ciphertext. Rotate them explicitly first.
begin;

do $migration$
begin
  if exists (
    select 1 from information_schema.columns
    where table_schema = 'public' and table_name = 'provider_oauth_tokens'
      and column_name = 'access_token'
  ) and exists (
    select 1 from public.provider_oauth_tokens
    where access_token is not null or refresh_token is not null
  ) then
    raise exception 'OAUTH_PLAINTEXT_ROTATION_REQUIRED';
  end if;
end
$migration$;

alter table public.provider_oauth_tokens
  add column if not exists access_token_ciphertext text,
  add column if not exists refresh_token_ciphertext text;

alter table public.provider_oauth_tokens
  drop column if exists access_token,
  drop column if exists refresh_token;

update public.provider_oauth_tokens
set token_type = 'Bearer'
where token_type is null;

alter table public.provider_oauth_tokens
  alter column access_token_ciphertext set not null,
  alter column token_type set default 'Bearer',
  alter column token_type set not null;

do $migration$
begin
  if not exists (
    select 1 from pg_constraint
    where conrelid = 'public.provider_oauth_tokens'::regclass
      and conname = 'provider_oauth_tokens_provider_check'
  ) then
    alter table public.provider_oauth_tokens
      add constraint provider_oauth_tokens_provider_check
      check (provider ~ '^[a-z0-9_-]{2,40}$');
  end if;
end
$migration$;

alter table public.provider_oauth_tokens enable row level security;
revoke all on table public.provider_oauth_tokens from anon, authenticated;
grant all on table public.provider_oauth_tokens to service_role;

comment on table public.provider_oauth_tokens is
  'Server-only encrypted OAuth credentials. Never expose through browser clients.';
comment on column public.provider_oauth_tokens.access_token_ciphertext is
  'AES-256-GCM ciphertext generated by the application; never plaintext.';
comment on column public.provider_oauth_tokens.refresh_token_ciphertext is
  'AES-256-GCM ciphertext generated by the application; never plaintext.';

commit;
