import fs from 'node:fs';
import path from 'node:path';
import os from 'node:os';
import {spawnSync} from 'node:child_process';
import {fileURLToPath} from 'node:url';
const root=path.resolve(path.dirname(fileURLToPath(import.meta.url)),'..');
const cwd=fs.mkdtempSync(path.join(os.tmpdir(),'opencode-professional-smoke-'));
fs.writeFileSync(path.join(cwd,'sum.cjs'),'module.exports = (a, b) => a - b;\n');
fs.writeFileSync(path.join(cwd,'sum.test.cjs'),"require('node:assert/strict').equal(require('./sum.cjs')(2,3),5); console.log('TEST_OK');\n");
fs.writeFileSync(path.join(cwd,'package.json'),JSON.stringify({name:'synthetic-test',scripts:{test:'node sum.test.cjs'}}));
spawnSync('git',['init','--quiet'],{cwd});
const before=spawnSync(process.execPath,['sum.test.cjs'],{cwd,encoding:'utf8'});
let key=process.env.FREELLMAPI_API_KEY;
if(!key)key=spawnSync('powershell.exe',['-NoProfile','-Command',"[Environment]::GetEnvironmentVariable('FREELLMAPI_API_KEY','User')"],{encoding:'utf8'}).stdout?.trim();
if(!key)throw new Error('Configure the unified key locally first');
const freeMode=process.argv.includes('--free');
const config=JSON.parse(fs.readFileSync(path.join(root,freeMode?'profiles/free.json':'profiles/global.json'),'utf8'));
for(const server of Object.values(config.mcp))server.enabled=false;
config.instructions=[path.join(root,'REGLAS.md')];
config.compaction.auto=false;
const exe=path.join(process.env.APPDATA,'npm/node_modules/opencode-ai/bin/opencode.exe');
const start=Date.now();
const run=spawnSync(exe,['run','--format','json','--agent','ingeniero','Lee sum.cjs. Corrige la función para sumar dos números, usando edit. Ejecuta npm test y responde LISTO solo si pasa.'],{cwd,env:{...process.env,FREELLMAPI_API_KEY:key,OPENCODE_COMPACT_TOOLS:'1',OPENCODE_WORKSTATION_HOME:root.replaceAll('\\','/'),OPENCODE_CONFIG_CONTENT:JSON.stringify(config)},encoding:'utf8',timeout:170000});
const after=spawnSync(process.execPath,['sum.test.cjs'],{cwd,encoding:'utf8'});
const events=String(run.stdout||'').split(/\r?\n/).flatMap(line=>{try{return [JSON.parse(line)]}catch{return []}});
const tools=events.filter(e=>e.type==='tool_use').map(e=>({tool:e.part?.tool,status:e.part?.state?.status}));
const report={date:new Date().toISOString(),model:config.model,syntheticOnly:true,initialTestFailed:before.status!==0,finalTestPassed:after.status===0,fileChanged:!fs.readFileSync(path.join(cwd,'sum.cjs'),'utf8').includes('a - b'),openCodeExit:run.status,timeout:run.error?.code==='ETIMEDOUT',runtimeSeconds:Math.round((Date.now()-start)/1000),tools,errors:events.filter(e=>e.type==='error').map(e=>e.error?.name||'error')};
fs.writeFileSync(path.join(root,freeMode?'development-smoke-free.json':'development-smoke.json'),JSON.stringify(report,null,2)+'\n');
console.log(JSON.stringify(report));
if(run.status!==0)console.log(String(run.stderr||'').replaceAll(key,'[hidden]').split(/\r?\n/).filter(x=>x.length<400).slice(0,20).join('\n'));
process.exitCode=after.status===0&&run.status===0?0:1;
